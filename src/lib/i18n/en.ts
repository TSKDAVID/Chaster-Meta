/** Same shape as `en`, with string leaves so locale catalogs can differ in wording. */
type StringLeaves<T> = {
  [K in keyof T]: T[K] extends string
    ? string
    : T[K] extends object
      ? StringLeaves<T[K]>
      : T[K];
};

